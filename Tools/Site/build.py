"""Render the prerelease static site from the maintained Markdown policy drafts."""

import argparse
import html
import re
from pathlib import Path
from string import Template
from urllib.parse import urlsplit, urlunsplit

from markdown_it import MarkdownIt

ROOT = Path(__file__).resolve().parents[2]
TOOLS = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
PAGES = {
    "privacy": (
        "SpamWise privacy policy",
        "How SpamWise handles mail, local data, optional cloud providers and your choices.",
    ),
    "support": (
        "SpamWise support",
        "Setup, corrections, provider troubleshooting and support for the SpamWise prerelease.",
    ),
    "lifecycle": (
        "Install, upgrade, recover and remove",
        "Managing SpamWise installation, backups, background operation and removal.",
    ),
    "mail-compatibility": (
        "Mail compatibility",
        "Observed Apple Mail compatibility and outstanding acceptance work for SpamWise.",
    ),
}


def markdown_content(source):
    """Preserve policy text while adding heading anchors and local HTML navigation."""
    renderer = MarkdownIt("commonmark", {"html": False}).enable("table")
    tokens = renderer.parse(source)
    for index, token in enumerate(tokens):
        if token.type == "heading_open":
            heading = tokens[index + 1].content.casefold()
            token.attrSet("id", re.sub(r"[^\w]+", "-", heading).strip("-"))
        for child in token.children or []:
            if child.type == "link_open":
                href = urlsplit(child.attrGet("href"))
                if (
                    not href.scheme
                    and not href.netloc
                    and href.path in {f"{page}.md" for page in PAGES}
                ):
                    child.attrSet(
                        "href", urlunsplit(href._replace(path=href.path[:-3] + ".html"))
                    )
    renderer.renderer.rules["table_open"] = lambda *_: (
        '<div class="table-scroll" role="region" aria-label="Compatibility table" tabindex="0"><table>\n'
    )
    renderer.renderer.rules["table_close"] = lambda *_: "</table></div>\n"
    return renderer.renderer.render(tokens, renderer.options, {})


def render_page(page, title, description, content, source):
    """Compose a script-free page with shared accessible navigation and footer."""
    navigation = "\n".join(
        f'<a href="{target}.html"'
        + (' aria-current="page"' if target == page else "")
        + f">{label}</a>"
        for target, label in (
            ("index", "Overview"),
            ("support", "Support"),
            ("privacy", "Privacy"),
        )
    )
    rendered = Template((TOOLS / "layout.html").read_text()).substitute(
        title=html.escape(title),
        description=html.escape(description, quote=True),
        navigation=navigation,
        page_class="home" if page == "index" else "document",
        content=content,
    )
    return rendered.replace(
        "<!doctype html>",
        f"<!doctype html>\n<!-- Generated by Tools/Site/build.py from {source}; edit the source. -->",
        1,
    )


def build(check):
    """Generate pages, or fail a read-only check when any generated page is stale."""
    pages = {
        "index": render_page(
            "index",
            "Your mail. Your rules.",
            "A prerelease Apple Mail filtering companion with explicit rules and explainable decisions. Free for macOS 27 or later.",
            (TOOLS / "home.html").read_text(),
            "Tools/Site/home.html",
        )
    }
    for page, (title, description) in PAGES.items():
        pages[page] = render_page(
            page,
            title,
            description,
            markdown_content((DOCS / f"{page}.md").read_text()),
            f"docs/{page}.md",
        )
    stale = []
    for page, content in pages.items():
        destination = DOCS / f"{page}.html"
        if not destination.exists() or destination.read_text() != content:
            if check:
                stale.append(str(destination.relative_to(ROOT)))
            else:
                destination.write_text(content)
    if stale:
        raise SystemExit("Stale generated pages: " + ", ".join(stale))
    print(f"{'Checked' if check else 'Generated'} {len(pages)} static pages.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
